"""Generate the pin headers from shared/pinmap.json.

Writes main/pins_gen.h (GPIO numbers, ADC channels, display and I2C constants)
and components/kestrel_core/include/ks_pinmap_gen.h (shift register bit
positions and the LED chain order). Run it again whenever the pin map changes.
"""
import json
import pathlib
import re

FW = pathlib.Path(__file__).resolve().parents[1]
PINMAP = FW.parent / "shared" / "pinmap.json"
BANNER = "// Generated by tools/gen_pins.py from shared/pinmap.json. Do not edit.\n"


def main() -> None:
    pm = json.loads(PINMAP.read_text(encoding="utf-8"))

    out = [BANNER, "#pragma once\n"]
    for num, pin in sorted(pm["gpio"].items(), key=lambda kv: int(kv[0])):
        out.append(f"#define PIN_{pin['net']} {num}")
        if "adc" in pin:
            unit, channel = re.fullmatch(r"ADC(\d)_CH(\d+)", pin["adc"]).groups()
            if unit != "1":
                raise SystemExit(f"{pin['net']} is on ADC{unit}; WiFi needs ADC1")
            out.append(f"#define ADC_CH_{pin['net']} {channel}")
    disp = pm["display"]
    offset = re.search(r"column offset (\d+)", disp["native"]).group(1)
    out += [
        "",
        f"#define LCD_WIDTH {disp['width']}",
        f"#define LCD_HEIGHT {disp['height']}",
        f"#define LCD_RAM_OFFSET {offset}",
        f"#define LCD_SPI_HZ {disp['spi_hz']}",
        f"#define LCD_SPI_MODE {disp['spi_mode']}",
        f"#define I2C_BUS_HZ {pm['i2c']['bus_speed_hz']}",
    ]
    for name, addr in pm["i2c"]["devices"].items():
        out.append(f"#define I2C_ADDR_{name} {addr}")
    (FW / "main" / "pins_gen.h").write_text("\n".join(out) + "\n", encoding="utf-8")

    core = [BANNER, "#pragma once\n",
            "// Bit index into the three bytes read from the 74HC165 chain:",
            "// index = 8 * register + input, where input A is bit 0 and H is bit 7."]
    for reg, sr in enumerate(("SR1", "SR2", "SR3")):
        for bit, letter in enumerate("ABCDEFGH"):
            core.append(f"#define KS_SR_{pm['shift_registers'][sr][letter]} {reg * 8 + bit}")
    chain = pm["leds"]["chain"]
    if len(chain) != pm["leds"]["count"]:
        raise SystemExit("LED chain length does not match leds.count")
    core += ["", f"#define KS_LED_COUNT {len(chain)}", "// Position of each LED in the data chain."]
    core += [f"#define KS_LED_{name} {i}" for i, name in enumerate(chain)]
    dest = FW / "components" / "kestrel_core" / "include" / "ks_pinmap_gen.h"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(core) + "\n", encoding="utf-8")
    print("wrote main/pins_gen.h and ks_pinmap_gen.h")


if __name__ == "__main__":
    main()

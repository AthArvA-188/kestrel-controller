"""Rasterise the UI fonts into components/kestrel_core/src/ks_font_data.c.

Uses Aileron Regular, the CC0 face that Pillow embeds, at three pixel sizes.
Each glyph is a cell of advance-width by line-height pixels at 4 bits per
pixel, two pixels per byte with the left pixel in the high nibble.
"""
import pathlib

from PIL import Image, ImageDraw, ImageFont

FW = pathlib.Path(__file__).resolve().parents[1]
DEST = FW / "components" / "kestrel_core" / "src" / "ks_font_data.c"
SIZES = (("small", 14), ("medium", 18), ("large", 34))
FIRST, LAST = 32, 126


def build(name: str, px: int) -> str:
    font = ImageFont.load_default(size=px)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    data, glyphs = [], []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        width = max(1, round(font.getlength(ch)))
        img = Image.new("L", (width, height), 0)
        ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=255)
        glyphs.append((len(data), width))
        px_data = img.load()
        for y in range(height):
            for x in range(0, width, 2):
                hi = (px_data[x, y] * 15 + 127) // 255
                lo = (px_data[x + 1, y] * 15 + 127) // 255 if x + 1 < width else 0
                data.append((hi << 4) | lo)
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    table = ", ".join(f"{{{off}, {w}}}" for off, w in glyphs)
    return (
        f"static const uint8_t {name}_data[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"
        f"static const ks_glyph_t {name}_glyphs[] = {{ {table} }};\n"
        f"const ks_font_t ks_font_{name} = {{ {height}, {ascent}, {FIRST}, {LAST}, "
        f"{name}_glyphs, {name}_data }};\n"
    )


def main() -> None:
    parts = ["// Generated by tools/gen_font.py from Aileron Regular (CC0). Do not edit.\n",
             '#include "ks_fb.h"\n']
    parts += [build(name, px) for name, px in SIZES]
    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {DEST.name}, {DEST.stat().st_size} bytes")


if __name__ == "__main__":
    main()
